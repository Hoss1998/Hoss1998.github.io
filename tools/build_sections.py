"""Build the Key Visuals and Print sections into sections.js.

KV and billboard picks are indexes into tools/kv_list.txt (paths relative to ~/Desktop/Hoss).
Print also includes every Zanussi client image.
"""
import json, os
from PIL import Image, ImageOps

Image.MAX_IMAGE_PIXELS = None
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HOSS = os.path.expanduser("~/Desktop/Hoss")
files = [l.strip()[2:] for l in open(os.path.join(ROOT, "tools/kv_list.txt")) if l.strip()]

KV = [  # (client slug, list index)
    ("bam", 0), *[("bimbo", i) for i in (1, 2, 3, 4)],
    *[("dominos", i) for i in range(5, 15)],
    *[("ghabour-auto", i) for i in range(15, 21)],
    *[("kasrawy", i) for i in range(26, 31)],
    ("larch", 31),
    *[("les-alpes", i) for i in (32, 33, 36, 37, 38, 39)],
    *[("ph", i) for i in (40, 41, 42, 43, 45, 47)],
    *[("sna", i) for i in range(49, 57)],
    *[("skoda", i) for i in (58, 59, 60)],
    *[("zanussi", i) for i in (61, 63)],
]
BILLBOARDS = [("kasrawy", i) for i in range(21, 26)]

def export(src, rel):
    im = ImageOps.exif_transpose(Image.open(src))
    if im.mode in ("RGBA", "LA", "P"):
        im = im.convert("RGBA"); bg = Image.new("RGB", im.size, "white"); bg.paste(im, mask=im.split()[-1]); im = bg
    im = im.convert("RGB"); im.thumbnail((1600, 1600), Image.LANCZOS)
    os.makedirs(os.path.dirname(os.path.join(ROOT, rel)), exist_ok=True)
    im.save(os.path.join(ROOT, rel), "JPEG", quality=82, optimize=True, progressive=True)
    return {"src": rel, "w": im.width, "h": im.height}

def build(picks, folder):
    out, count = [], {}
    for slug, i in picks:
        count[slug] = count.get(slug, 0) + 1
        out.append({"slug": slug, **export(os.path.join(HOSS, files[i]), f"images/{folder}/{slug}-{count[slug]:02d}.jpg")})
    return out

js = open(os.path.join(ROOT, "projects.js"), encoding="utf-8").read()
clients = json.loads(js[js.index("["):js.rindex("]") + 1])
zanussi = next(c for c in clients if c["slug"] == "zanussi")
kv = build(KV, "kv")
prints = [{"slug": "zanussi", **im} for im in zanussi["images"]] + build(BILLBOARDS, "print")
with open(os.path.join(ROOT, "sections.js"), "w", encoding="utf-8") as f:
    f.write("// Generated by tools/build_sections.py\n")
    f.write("const KEY_VISUALS = " + json.dumps(kv, indent=1) + ";\n")
    f.write("const PRINTS = " + json.dumps(prints, indent=1) + ";\n")
print(f"{len(kv)} key visuals, {len(prints)} prints")
